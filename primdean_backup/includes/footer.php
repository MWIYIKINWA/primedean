<!-- Cookie Banner Logic -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const banner = document.getElementById('cookie-banner');
        const acceptBtn = document.getElementById('accept-cookies');
        const declineBtn = document.getElementById('decline-cookies');

        // 1. Check if the 'cookie_consent' cookie already exists
        if (!document.cookie.split('; ').find(row => row.startsWith('cookie_consent='))) {
            // Show banner by removing 'hidden', then triggering the slide-up animation
            banner.classList.remove('hidden');
            setTimeout(() => {
                banner.classList.remove('translate-y-full');
            }, 100); // Slight delay ensures CSS transition triggers
        }

        // 2. Function to set the cookie and hide the banner
        function setCookieConsent(value) {
            const date = new Date();
            // Set expiry for 365 days
            date.setTime(date.getTime() + (365 * 24 * 60 * 60 * 1000));
            document.cookie = "cookie_consent=" + value + ";expires=" + date.toUTCString() + ";path=/;SameSite=Lax";

            // Slide banner down
            banner.classList.add('translate-y-full');

            // Hide completely after animation finishes
            setTimeout(() => {
                banner.classList.add('hidden');
            }, 500);
        }

        // 3. Event Listeners for buttons
        acceptBtn.addEventListener('click', () => setCookieConsent('accepted'));
        declineBtn.addEventListener('click', () => setCookieConsent('declined'));
    });
</script>

<!-- Scroll & Interactivity Script -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const goToTopBtn = document.getElementById('goToTopBtn');

        // Toggle visibility based on scroll depth
        window.addEventListener('scroll', () => {
            if (window.scrollY > 400) {
                // Show button
                goToTopBtn.classList.remove('opacity-0', 'pointer-events-none', 'translate-y-4');
                goToTopBtn.classList.add('opacity-100', 'pointer-events-auto', 'translate-y-0');
            } else {
                // Hide button
                goToTopBtn.classList.add('opacity-0', 'pointer-events-none', 'translate-y-4');
                goToTopBtn.classList.remove('opacity-100', 'pointer-events-auto', 'translate-y-0');
            }
        });

        // Smooth scroll to top on click
        goToTopBtn.addEventListener('click', () => {
            window.scrollTo({
                top: 0,
                behavior: 'smooth'
            });
        });
    });
</script>



